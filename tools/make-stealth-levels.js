/* A copy of all 196 levels under the Stealth rules (src/stealth.js): same maps, the new par, and the number of lures each level comes with
   (the fewest that still gives the best par; none when a lure does not help). Writes play/stealth-levels.js.   node tools/make-stealth-levels.js */
'use strict';
const fs = require('fs'), vm = require('vm'), path = require('path');
const P = require('../src/prison.js'), S = require('../src/stealth.js');
global.window = {}; vm.runInThisContext(fs.readFileSync(path.join(__dirname, '..', 'play', 'levels.js'), 'utf8'));
const BASE = { camNear: 2, guardNear: 1, crawl: 1, throwR: 3, hearR: 4, lureStep: 1 };
const run = (L, lures) => { L.stealth = Object.assign({}, BASE, { lures }); return S.solveStealth(L, { maxStates: 900000 }); };
const out = [], t0 = Date.now(); let lowered = 0, lured = 0;
for (const lv of window.PRISON_LEVELS) {
  const L = P.parseLevel(lv.map, lv.meta), B = run(L, 0), C = L.guards.length ? run(L, 2) : B;
  if (!B || !B.solvable) throw new Error('level ' + lv.id + ' unsolvable under the new rules');
  let lures = 0, par = B.par;
  if (C && C.solvable && C.par < B.par) { lures = run(L, 1).par === C.par ? 1 : 2; par = C.par; }
  if (par < lv.par) lowered++; if (lures) lured++;
  out.push({ id: lv.id, map: lv.map, meta: lv.meta, classicPar: lv.par, crawlPar: B.par, par, stealth: Object.assign({}, BASE, { lures }) });
}
fs.writeFileSync(path.join(__dirname, '..', 'play', 'stealth-levels.js'), '/* generated by tools/make-stealth-levels.js: all levels re-solved under the Stealth rules */\nwindow.STEALTH_LEVELS = ' + JSON.stringify(out) + ';\n');
console.log('wrote play/stealth-levels.js', { levels: out.length, lowered, lured, ms: Date.now() - t0 });
