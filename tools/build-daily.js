/* Builds play/daily.js (the daily-challenge bank) from the parts made by tools/gen-daily.js.
   Every level is re-solved from its picture (par must match), must still be a SHIELD level (the prisoner starts dark when guards do not block sight, and without a guard in a beam
   the way out is at least shieldMin longer, or gone), and must not look like a numbered level or another day's level (wall pattern, 8 symmetries, overlap < MAX_SIM).
   usage: node tools/build-daily.js <startDate YYYY-MM-DD> <days> <part.jsonl>... [--out play/daily.js] [--rejects file]    (days = 365)
   Days or tiers that are missing or rejected are written to the rejects file as "day tier" lines: run gen-daily for them again with another SEED_OFFSET. */
'use strict';
const fs = require('fs'), P = require('../src/prison.js');
const args = process.argv.slice(2), opt = n => { const i = args.indexOf('--' + n); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const outFile = opt('out') || 'play/daily.js', rejFile = opt('rejects') || null;
const [start, days, ...parts] = args; const N = Number(days);
if (!/^\d{4}-\d{2}-\d{2}$/.test(start || '') || !N || !parts.length) { console.error('usage: node tools/build-daily.js <startDate> <days> <part.jsonl>... [--out f] [--rejects f]'); process.exit(2); }
const MAX_SIM = 0.8;
const BLOCKED = new Set([...'#^>v<0123pqrG']);
const sig = map => ({ w: map[0].length, h: map.length, b: map.map(r => [...r].map(c => BLOCKED.has(c))) });
function variants(s) {                                                   // the pattern as it looks flipped / turned
  const out = [], rows = s.b, h = rows.length, w = rows[0].length;
  const flipX = g => g.map(r => r.slice().reverse()), flipY = g => g.slice().reverse(), tr = g => g[0].map((_, x) => g.map(r => r[x]));
  const base = [rows, flipX(rows), flipY(rows), flipY(flipX(rows))];
  for (const g of base) { out.push(g); if (w === h) out.push(tr(g)); }
  return out;
}
function sim(a, b) {                                                     // best overlap (intersection over union of the blocked cells) over the symmetries
  if (a.w * a.h !== b.w * b.h) return 0;
  let best = 0;
  for (const v of variants(b)) {
    if (v.length !== a.h || v[0].length !== a.w) continue;
    let i = 0, u = 0;
    for (let y = 0; y < a.h; y++) for (let x = 0; x < a.w; x++) { const p = a.b[y][x], q = v[y][x]; if (p && q) i++; if (p || q) u++; }
    best = Math.max(best, u ? i / u : 0);
  }
  return best;
}
const shipped = []; { global.window = {}; require('../play/levels.js'); for (const l of window.PRISON_LEVELS) shipped.push(sig(l.map)); }
const recs = {};
for (const f of parts) for (const l of fs.readFileSync(f, 'utf8').split('\n')) if (l.trim()) { const d = JSON.parse(l); const k = d.day + ':' + d.tier; (recs[k] = recs[k] || []).push(d); }
const bank = [], rejects = [], kept = []; const why = {};
const bad = (k, r) => { why[r] = (why[r] || 0) + 1; return null; };
function check(d) {
  const back = P.parseLevel(d.map, d.meta); P.prepare(back);
  const s = P.solve(back, { maxDepth: 40 }); if (!s || !s.solvable || s.par !== d.par) return 'resolve';
  const G = P.ghostOf(back); P.prepare(G); const e = P.evalConfig(G, P.initialDigits(G), false); if (e.lit[back.S] || e.occ[back.S]) return 'start-lit';
  const rg = P.solve(G, { maxDepth: 40 }); if (rg && rg.solvable && rg.par < d.par + 1) return 'not-shield';
  const sg = sig(d.map);
  for (const o of shipped) if (sim(sg, o) >= MAX_SIM) return 'like-numbered';
  for (const o of kept) if (sim(sg, o) >= MAX_SIM) return 'like-daily';
  d._sig = sg; return null;
}
for (let day = 0; day < N; day++) {
  const row = [];
  for (let tier = 0; tier < 3; tier++) {
    const cand = recs[day + ':' + tier] || []; let ok = null, r = 'missing';
    for (const d of cand) { r = check(d); if (!r) { ok = d; break; } }
    if (!ok) { bad(day, r); rejects.push(day + ' ' + tier); row.push(null); continue; }
    kept.push(ok._sig); row.push({ map: ok.map, meta: ok.meta, par: ok.par });
  }
  bank.push(row);
}
const missing = rejects.length;
console.error(`${N * 3 - missing} of ${N * 3} levels accepted; rejected/missing: ${missing}`, JSON.stringify(why));
if (rejFile) fs.writeFileSync(rejFile, rejects.join('\n') + (rejects.length ? '\n' : ''));
if (missing) { console.error('not writing ' + outFile + ' (the bank must be complete); fix the rejects first'); process.exit(1); }
fs.writeFileSync(outFile, '/* generated by tools/gen-daily.js + tools/build-daily.js: ' + N + ' days x 3 shield levels (easy, medium, hard); day = UTC date, index = days since start mod length */\nwindow.PRISON_DAILY = ' + JSON.stringify({ start, days: bank }) + ';\n');
console.error('wrote ' + outFile + ' (' + fs.statSync(outFile).size + ' bytes)');
